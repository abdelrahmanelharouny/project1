"""Deterministic synthetic satellite provider (P2.A software fixture).

Generates *labelled synthetic* vegetation-index scenes for testing the
satellite intelligence pipeline end to end — they are NOT real satellite
observations and carry no agronomic validity. Every observation is flagged
`is_synthetic=True` with the generator version, seed and profile recorded in
provenance and per-row metadata (same discipline as the weather fixture).

Determinism: the same (seed, profile, variables, date range, AOI) yields
byte-identical series; generation uses Python's `random` seeded from a hash
of the full request signature — never wall-clock time.

Scene model (fixture constants, not sensor claims):
- 5-day revisit from the requested start.
- Band-level SURFACE REFLECTANCES are generated per scene and pushed through
  `app.vegetation.indices.compute_indices`, so index values exercise the real
  formula code path (NDVI/EVI/SAVI/NDMI/NDWI).
- Cloud episodes: deterministic per scene; a cloudy scene produces
  CLOUD_OCCLUDED quality flags and missing values — the honest
  missing-observation path.

Profiles are fixture shapes: `cropland_seasonal` (healthy double season),
`stress_declining` (late-season decline), `constant_moderate` (flat series).
"""

import hashlib
import json
import math
import random
from datetime import UTC, datetime, timedelta
from typing import Any

from pydantic import BaseModel

from app.core.errors import InvalidDateRange
from app.data_platform.contracts.observations import (
    AreaOfInterest,
    CanonicalObservation,
    EvidenceClass,
    ProviderFetchResult,
    QualityStatus,
    SourceProvenance,
    TimeSupport,
)
from app.vegetation.indices import compute_indices, supported_indices

PROVIDER_CODE = "satellite_sim"
PROVIDER_NAME = "CropTwist Synthetic Satellite Fixture"
GENERATOR_VERSION = "satellite-sim-v1.0"
PRODUCT_CODE = "satellite_sim_fixture"
PRODUCT_VERSION = "v1"
COVERAGE_START = datetime(2016, 1, 1, tzinfo=UTC)
COVERAGE_END = datetime(2026, 12, 31, tzinfo=UTC)

REVISIT_DAYS = 5
SCENE_SPATIAL_RESOLUTION_M = 10.0


class SimProfile(BaseModel):
    """Fixture shape parameters. Synthetic-test constants only."""

    base_ndvi: float
    seasonality: float
    decline_rate: float  # NDVI units per year over the series (fixture trend)
    cloud_probability: float
    description: str


PROFILES: dict[str, SimProfile] = {
    "cropland_seasonal": SimProfile(
        base_ndvi=0.45,
        seasonality=0.32,
        decline_rate=0.0,
        cloud_probability=0.18,
        description="Synthetic cropland fixture with seasonal greening/dormancy cycle.",
    ),
    "stress_declining": SimProfile(
        base_ndvi=0.52,
        seasonality=0.28,
        decline_rate=-0.06,
        cloud_probability=0.15,
        description="Synthetic fixture with a steady vegetation decline (stress test shape).",
    ),
    "constant_moderate": SimProfile(
        base_ndvi=0.5,
        seasonality=0.05,
        decline_rate=0.0,
        cloud_probability=0.12,
        description="Synthetic near-constant moderate-vigor fixture.",
    ),
}

PROFILE_CODES = sorted(PROFILES.keys())


def _request_rng(seed: int, profile: str, aoi: AreaOfInterest, variables: list[str],
                 start: datetime, end: datetime) -> random.Random:
    payload = json.dumps(
        {
            "seed": seed,
            "profile": profile,
            "aoi": aoi.geometry_geojson,
            "variables": sorted(variables),
            "start": start.isoformat(),
            "end": end.isoformat(),
        },
        sort_keys=True,
    )
    digest = hashlib.sha256(payload.encode("utf-8")).hexdigest()
    return random.Random(int(digest[:16], 16))


def _day_of_year_phase(day: datetime) -> float:
    """0..1 seasonal phase (peak green at day ~200 northern-hemisphere shape)."""
    doy = day.timetuple().tm_yday
    return math.cos(2.0 * math.pi * (doy - 200) / 365.25)  # 1 at peak, -1 at trough


class SatelliteSimProvider:
    """Synthetic satellite fixture implementing the provider contract."""

    provider_code = PROVIDER_CODE

    def profiles(self) -> list[dict[str, Any]]:
        return [{"code": c, "description": p.description} for c, p in sorted(PROFILES.items())]

    def supported_variables(self) -> list[str]:
        return supported_indices()

    def _provenance(self) -> SourceProvenance:
        return SourceProvenance(
            provider_code=PROVIDER_CODE,
            provider_name=PROVIDER_NAME,
            product_code=PRODUCT_CODE,
            product_version=PRODUCT_VERSION,
            license_name="MIT (fixture code)",
            license_url="https://opensource.org/licenses/MIT",
            attribution_text=(
                "SYNTHETIC SATELLITE FIXTURE — generated by CropTwist; not real "
                "satellite data; no agronomic validity."
            ),
            documentation_url=None,
            known_limitations=(
                "Fixture shapes are invented (5-day revisit, idealized reflectances). "
                "Do not use for any real-world agronomic conclusion."
            ),
            retrieval_method="in_process_generator",
        )

    def _scene_reflectances(
        self, params: SimProfile, day: datetime, rng: random.Random
    ) -> dict[str, float]:
        """Generate physically plausible surface reflectances for one scene."""
        phase = _day_of_year_phase(day)
        ndvi_target = (
            params.base_ndvi
            + params.seasonality * phase
            + params.decline_rate * ((day.year - COVERAGE_START.year) + day.timetuple().tm_yday / 365.25)
        )
        ndvi_target = max(-0.1, min(0.92, ndvi_target))
        # Invert a simple 2-band reflectance model: red ~ 0.12*(1-NDVI)+noise,
        # nir ~ 0.30*(1+NDVI)+noise, then scale to keep NDVI near target.
        red = max(0.02, min(0.6, 0.30 * (1.0 - ndvi_target) + rng.gauss(0.0, 0.012)))
        nir = max(0.03, min(0.75, 0.34 * (1.0 + ndvi_target) + rng.gauss(0.0, 0.014)))
        blue = max(0.02, min(0.5, red * 0.8 + rng.gauss(0.0, 0.01)))
        green = max(0.02, min(0.55, red * 1.05 + rng.gauss(0.0, 0.01)))
        swir1 = max(0.03, min(0.6, 0.42 - 0.2 * ndvi_target + rng.gauss(0.0, 0.015)))
        return {"red": red, "nir": nir, "blue": blue, "green": green, "swir1": swir1}

    def fetch_observations(
        self,
        *,
        area_of_interest: AreaOfInterest,
        variables: list[str],
        start: datetime,
        end: datetime,
        options: dict[str, Any] | None = None,
    ) -> ProviderFetchResult:
        options = options or {}
        start = start.astimezone(UTC)
        end = end.astimezone(UTC)
        if start < COVERAGE_START or end > COVERAGE_END:
            raise InvalidDateRange(
                "Synthetic satellite fixture coverage is 2016-01-01..2026-12-31.",
                details=[
                    {
                        "field": "date_range",
                        "reason": f"requested {start.date()}..{end.date()} outside provider coverage",
                    }
                ],
            )
        if (end - start).days > 366 * 4:
            raise InvalidDateRange("Synthetic satellite fixture requests are limited to 4 years per job.")

        profile = options.get("profile", "cropland_seasonal")
        if profile not in PROFILES:
            raise InvalidDateRange(
                f"Unknown synthetic satellite profile '{profile}'.",
                details=[{"field": "profile", "reason": f"choose one of {', '.join(PROFILE_CODES)}"}],
            )
        unknown = sorted(set(variables) - set(self.supported_variables()))
        if unknown:
            raise InvalidDateRange(
                f"Variables not produced by this provider: {', '.join(unknown)}.",
                details=[{"field": "variables", "reason": "satellite_sim produces vegetation indices only"}],
            )
        seed = int(options.get("seed", 7))
        params = PROFILES[profile]
        rng = _request_rng(seed, profile, area_of_interest, variables, start, end)

        observations: list[CanonicalObservation] = []
        warnings: list[str] = [
            "All observations from this provider are SYNTHETIC satellite fixtures; "
            "they must never be presented as real satellite measurements."
        ]
        scene_counter = 0
        scene_day = start.replace(hour=10, minute=0, second=0, microsecond=0)
        while scene_day <= end:
            scene_counter += 1
            scene_id = f"SIM-{profile.upper()}-{scene_day.strftime('%Y%m%d')}-{seed:05d}"
            cloudy = rng.random() < params.cloud_probability
            reflectances: dict[str, float] | None = None
            cloud_pct = round(min(97.0, 30.0 + rng.random() * 65.0), 1) if cloudy else round(rng.random() * 18.0, 1)
            if not cloudy:
                reflectances = self._scene_reflectances(params, scene_day, rng)
            for vcode in sorted(set(variables)):
                metadata: dict[str, Any] = {
                    "scene_id": scene_id,
                    "granule_id": scene_id,
                    "sensor": "satellite_sim",
                    "spatial_resolution_m": SCENE_SPATIAL_RESOLUTION_M,
                    "cloud_cover_pct": cloud_pct,
                    "quality_flags": (
                        [{"flag_code": "CLOUD_OCCLUDED", "severity": "warning",
                          "message": "Fixture cloud episode; index not retrieved."}]
                        if cloudy
                        else [{"flag_code": "SIM Fixture data", "severity": "info",
                               "message": "Synthetic fixture scene."}]
                    ),
                    "generator_version": GENERATOR_VERSION,
                    "profile": profile,
                    "seed": seed,
                    "raster_url": None,
                    "is_synthetic": True,
                }
                if cloudy or reflectances is None:
                    value = None
                    quality = QualityStatus.missing
                else:
                    computed = compute_indices(
                        sensor="sentinel2", reflectances=reflectances, indices=[vcode]
                    )
                    value = computed.values.get(vcode)
                    quality = QualityStatus.valid if value is not None else QualityStatus.missing
                observations.append(
                    CanonicalObservation(
                        variable_code=vcode,
                        value=value,
                        unit="index",
                        observed_at=scene_day,
                        period_start=scene_day,
                        period_end=scene_day,
                        time_support=TimeSupport.instant,
                        spatial_support_type=SpatialSupportType.grid_cell,
                        spatial_resolution_m=SCENE_SPATIAL_RESOLUTION_M,
                        quality_status=quality,
                        uncertainty_value=0.02 if value is not None else None,
                        uncertainty_type="fixture_constant",
                        evidence_class=EvidenceClass.satellite_derived_estimate,
                        is_synthetic=True,
                        processing_version=GENERATOR_VERSION,
                        metadata=metadata,
                        quality_flags=metadata["quality_flags"],
                    )
                )
            scene_day += timedelta(days=REVISIT_DAYS)

        return ProviderFetchResult(
            provider_code=PROVIDER_CODE,
            provenance=self._provenance(),
            observations=observations,
            warnings=warnings,
            coverage={
                "start": start.isoformat(),
                "end": end.isoformat(),
                "scenes": scene_counter,
                "revisit_days": REVISIT_DAYS,
            },
            provider_request_id=f"satellite-sim-{seed}",
            raw_reference=None,
            input_record_count=len(observations),
        )
