            "Quasi-global LAND rainfall product (~60N-60S, 0.05 deg grid); no ocean "
            "coverage and not global. Daily (esp. downscaled) fields must not be used "
            "as unquestioned evidence for daily extremes; prefer pentad/monthly for "
            "climate summaries."
