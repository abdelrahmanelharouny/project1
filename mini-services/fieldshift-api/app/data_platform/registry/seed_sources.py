"""Seed the data_sources / dataset_products registry (Master §13.2).

Only the synthetic source exists in this slice. Real providers (Open-Meteo,
CHIRPS v3, SoilGrids) are added by later milestones with full metadata.
"""

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.data_platform.providers.synthetic.provider import (
    GENERATOR_VERSION,
    PRODUCT_CODE,
    PRODUCT_VERSION,
    PROVIDER_CODE,
    PROVIDER_NAME,
    COVERAGE_START,
    COVERAGE_END,
)
from app.db.models import DataSource, DatasetProduct


def seed_data_registry(db: Session) -> None:
    source = db.scalar(select(DataSource).where(DataSource.provider_code == PROVIDER_CODE))
    if source is None:
        source = DataSource(
            provider_code=PROVIDER_CODE,
            provider_name=PROVIDER_NAME,
            base_url=None,
            license_name="MIT (fixture code)",
            license_url="https://opensource.org/licenses/MIT",
            attribution_text=(
                "SYNTHETIC TEST FIXTURE — generated by FieldShift; not real-world data."
            ),
            documentation_url=None,
            status="active",
            known_limitations=(
                "Synthetic profiles are invented fixture shapes. Never use for real-world "
                "agronomic conclusions. All rows carry is_synthetic=true."
            ),
        )
        db.add(source)
        db.flush()

    product = db.scalar(
        select(DatasetProduct).where(
            DatasetProduct.source_id == source.id,
            DatasetProduct.product_code == PRODUCT_CODE,
            DatasetProduct.product_version == PRODUCT_VERSION,
        )
    )
    if product is None:
        db.add(
            DatasetProduct(
                source_id=source.id,
                product_code=PRODUCT_CODE,
                product_version=PRODUCT_VERSION,
                description="Deterministic synthetic daily weather fixture (5 profiles).",
                spatial_resolution_m=None,
                temporal_resolution="daily",
                coverage_start=COVERAGE_START,
                coverage_end=COVERAGE_END,
                metadata={
                    "generator_version": GENERATOR_VERSION,
                    "is_synthetic": True,
                    "evidence_class": "synthetic_test_data",
                },
            )
        )
    db.commit()
