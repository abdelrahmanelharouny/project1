"""Seed the data_sources / dataset_products registry (Master §13.2).

Every provider that can land observations has a registered source + product
with license, attribution and known limitations — this is what the Data
Passport and the UI display, so it must stay complete and honest.
"""

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.data_platform.providers.chirps.registry_info import (
    PRODUCT_FAMILY as CHIRPS_PRODUCT_FAMILY,
    PROVIDER_CODE as CHIRPS_CODE,
    PROVIDER_NAME as CHIRPS_NAME,
)
from app.data_platform.providers.open_meteo.provider import (
    COVERAGE_START as OM_COVERAGE_START,
    MODELS as OM_MODELS,
    PRODUCT_VERSION as OM_PRODUCT_VERSION,
    PROVIDER_CODE as OM_CODE,
    PROVIDER_NAME as OM_NAME,
)
from app.data_platform.providers.soilgrids.provider import (
    DEPTH as SG_DEPTH,
    PRODUCT_CODE as SG_PRODUCT_CODE,
    PRODUCT_VERSION as SG_PRODUCT_VERSION,
    PROVIDER_CODE as SG_CODE,
    PROVIDER_NAME as SG_NAME,
)
from app.data_platform.providers.synthetic.provider import (
    COVERAGE_START,
    COVERAGE_END,
    GENERATOR_VERSION,
    PRODUCT_CODE,
    PRODUCT_VERSION,
    PROVIDER_CODE,
    PROVIDER_NAME,
)
from app.db.models import DataSource, DatasetProduct


def _ensure_source(db: Session, **kwargs) -> DataSource:
    source = db.scalar(select(DataSource).where(DataSource.provider_code == kwargs["provider_code"]))
    if source is None:
        source = DataSource(**kwargs)
        db.add(source)
        db.flush()
    return source


def _ensure_product(db: Session, source_id, **kwargs) -> DatasetProduct:
    product = db.scalar(
        select(DatasetProduct).where(
            DatasetProduct.source_id == source_id,
            DatasetProduct.product_code == kwargs["product_code"],
            DatasetProduct.product_version == kwargs["product_version"],
        )
    )
    if product is None:
        db.add(DatasetProduct(source_id=source_id, **kwargs))
        db.flush()
    return product


def seed_data_registry(db: Session) -> None:
    # ------------------------------------------------ synthetic fixtures
    source = _ensure_source(
        db,
        provider_code=PROVIDER_CODE,
        provider_name=PROVIDER_NAME,
        base_url=None,
        license_name="MIT (fixture code)",
        license_url="https://opensource.org/licenses/MIT",
        attribution_text=(
            "SYNTHETIC TEST FIXTURE — generated by FieldShift; not real-world data."
        ),
        documentation_url=None,
        status="active",
        known_limitations=(
            "Synthetic profiles are invented fixture shapes. Never use for real-world "
            "agronomic conclusions. All rows carry is_synthetic=true."
        ),
    )
    _ensure_product(
        db,
        source.id,
        product_code=PRODUCT_CODE,
        product_version=PRODUCT_VERSION,
        description="Deterministic synthetic daily weather fixture (5 profiles).",
        spatial_resolution_m=None,
        temporal_resolution="daily",
        coverage_start=COVERAGE_START,
        coverage_end=COVERAGE_END,
        metadata={
            "generator_version": GENERATOR_VERSION,
            "is_synthetic": True,
            "evidence_class": "synthetic_test_data",
        },
    )

    # ------------------------------------------------ Open-Meteo archive
    om_source = _ensure_source(
        db,
        provider_code=OM_CODE,
        provider_name=OM_NAME,
        base_url="https://archive-api.open-meteo.com/v1/archive",
        license_name="CC BY 4.0",
        license_url="https://creativecommons.org/licenses/by/4.0/",
        attribution_text=(
            "Weather data by Open-Meteo.com (CC BY 4.0), built on ERA5 / ERA5-Land "
            "reanalysis (Copernicus Climate Change Service / ECMWF)."
        ),
        documentation_url="https://open-meteo.com/en/docs/historical-weather-api",
        status="active",
        known_limitations=(
            "Gridded reanalysis estimate for the field centroid cell — not a field "
            "sensor. ERA5-Land is land-only (~9-11 km cells); ERA5 is ~28 km. Daily "
            "values are aggregates of hourly model output."
        ),
    )
    for code, model in OM_MODELS.items():
        _ensure_product(
            db,
            om_source.id,
            product_code=code,
            product_version=OM_PRODUCT_VERSION,
            description=model.description,
            spatial_resolution_m=model.spatial_resolution_m,
            temporal_resolution="daily",
            coverage_start=OM_COVERAGE_START,
            coverage_end=None,  # rolling archive (a few days behind present)
            metadata={"evidence_class": "reanalysis_model_estimate", "is_synthetic": False},
        )

    # ------------------------------------------------ CHIRPS v3 (file import)
    chirps_source = _ensure_source(
        db,
        provider_code=CHIRPS_CODE,
        provider_name=CHIRPS_NAME,
        base_url="https://www.chc.ucsb.edu/data/chirps3",
        license_name="Public domain (CHC)",
        license_url="https://www.chc.ucsb.edu/data/chirps3",
        attribution_text=(
            "CHIRPS v3.0 — Climate Hazards Center, UC Santa Barbara. Product variant "
            "and preliminary/final status are recorded per observation."
        ),
        documentation_url="https://www.chc.ucsb.edu/data/chirps3",
        status="active",
        known_limitations=(
            "Quasi-global LAND rainfall product (~60N-60S, 0.05 deg grid); no ocean "
            "coverage and not global. Daily (esp. downscaled) fields must not be used "
            "as unquestioned evidence for daily extremes; prefer pentad/monthly for "
            "climate summaries."
        ),
    )
    for kind in ("daily", "pentad", "monthly"):
        for status_ in ("preliminary", "final"):
            _ensure_product(
                db,
                chirps_source.id,
                product_code=f"{CHIRPS_PRODUCT_FAMILY}_{kind}",
                product_version=f"v3.0-{status_}",
                description=f"CHIRPS v3.0 {kind} {status_} product (imported GeoTIFF, field extract).",
                spatial_resolution_m=5566.0,
                temporal_resolution=kind,
                coverage_start=None,
                coverage_end=None,  # defined by the imported files
                metadata={"evidence_class": "satellite_derived_estimate", "is_synthetic": False},
            )

    # ------------------------------------------------ SoilGrids (optional WCS)
    sg_source = _ensure_source(
        db,
        provider_code=SG_CODE,
        provider_name=SG_NAME,
        base_url="https://maps.isric.org/mapserv",
        license_name="CC BY 4.0",
        license_url="https://creativecommons.org/licenses/by/4.0/",
        attribution_text="SoilGrids 2.0 soil property predictions — ISRIC World Soil Information (CC BY 4.0).",
        documentation_url="https://docs.isric.org/globaldata/soilgrids/wcs.html",
        status="optional",
        known_limitations=(
            "Global model prediction with quantified uncertainty over ~250 m cells — "
            "never a substitute for laboratory soil analysis. Static snapshot (2020 "
            "release), not a time series. REST API paused; WCS access used; the "
            "provider degrades gracefully when the WCS is unavailable."
        ),
    )
    _ensure_product(
        db,
        sg_source.id,
        product_code=SG_PRODUCT_CODE,
        product_version=SG_PRODUCT_VERSION,
        description="SoilGrids 2.0 predicted soil properties (0-5 cm slice-2 depth, Qmean + Q0.05/Q0.95).",
        spatial_resolution_m=250.0,
        temporal_resolution="instant",
        coverage_start=None,
        coverage_end=None,
        metadata={
            "evidence_class": "global_soil_prediction",
            "is_synthetic": False,
            "depth": SG_DEPTH,
        },
    )

    # ------------------------------------------------ farmer CSV import
    farmer_source = _ensure_source(
        db,
        provider_code="farmer_csv",
        provider_name="Farmer CSV Import",
        base_url=None,
        license_name=None,
        license_url=None,
        attribution_text="Records supplied by the farmer/operator via CSV import.",
        documentation_url="/api/v1/data/imports/observations-csv/template",
        status="active",
        known_limitations=(
            "Farmer-reported records are unverified personal observations; they carry "
            "the farmer_reported_record evidence class and are never mixed silently "
            "with instrument or model data."
        ),
    )
    _ensure_product(
        db,
        farmer_source.id,
        product_code="farmer_record",
        product_version="v1",
        description="Farmer-supplied observations imported from validated CSV files.",
        spatial_resolution_m=None,
        temporal_resolution="daily",
        coverage_start=None,
        coverage_end=None,
        metadata={"evidence_class": "farmer_reported_record", "is_synthetic": False},
    )

    db.commit()
