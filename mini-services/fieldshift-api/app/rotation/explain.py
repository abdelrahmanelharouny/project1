"""Explainability & decision evidence (Milestone 5.6).

Builds the explanation blocks attached to every strategy: why it was
generated, why recommended/excluded, constraint outcomes, evidence references
(knowledge citations + feature-run provenance), data limitations, expected
benefits vs baseline, risks/trade-offs, and the local expert validation
requirements (reference-status knowledge that a regional agronomist must
confirm before operational use).
"""

from __future__ import annotations

from typing import Any

from app.rotation.constraints import all_satisfied
from app.rotation.objectives import CRITERION_DIRECTIONS, CRITERION_UNITS
from app.rotation.problem import (
    RotationProblem,
    StrategySolution,
)


def _criteria_by_code(solution: StrategySolution) -> dict[str, Any]:
    return {c.criterion_code: c for c in solution.criteria}


def build_explanations(
    problem: RotationProblem,
    solution: StrategySolution,
    all_solutions: list[StrategySolution],
) -> dict[str, Any]:
    criteria = _criteria_by_code(solution)
    feasible = all_satisfied(list(solution.constraints_checked))

    why_generated = (
        "Baseline reconstructed from the field's crop history — evaluated as-is."
        if solution.is_baseline
        else (
            f"Generated by the CP-SAT optimizer under the '{solution.strategy_key}' "
            "preference profile: hard constraints (admissible candidates only, "
            "confirmed rotation rules, water allocation when supplied) plus a weighted "
            "soft objective over the criteria that were evaluable from evidence."
        )
    )

    # why recommended / excluded
    if solution.is_baseline:
        why = (
            "Baseline is shown for comparison; it is NOT modified to look feasible."
            if feasible
            else "Baseline violates at least one active hard constraint — shown "
            "honestly as the starting point, never as a recommendation."
        )
        recommendation = {"status": "baseline", "message": why}
    elif not feasible:
        recommendation = {
            "status": "invalid",
            "message": "Strategy violates a hard constraint and must not be adopted "
            "(reporting bug if a solver result ever reaches this state).",
        }
    elif solution.on_pareto_front:
        dominated = solution.dominates
        recommendation = {
            "status": "recommended",
            "message": "On the Pareto front of the generated strategy set — no other "
            "generated strategy is better on every evaluable criterion."
            + (f" Dominates: {', '.join(dominated)}." if dominated else ""),
        }
    else:
        recommendation = {
            "status": "dominated",
            "message": f"Dominated by {', '.join(solution.dominated_by)} on the shared "
            "evaluable criteria — kept for transparency and trade-off inspection.",
        }

    # evidence references
    evidence_refs: list[dict[str, Any]] = []
    for ref in problem.knowledge.pack_refs:
        evidence_refs.append({"type": "knowledge_pack", **ref})
    for label, run_id in problem.farm.climate_run_refs.items():
        evidence_refs.append({
            "type": "feature_run",
            "season_label": label,
            "feature_run_id": run_id,
        })
    trait_sources: dict[tuple[str, str], dict[str, Any]] = {}
    for label, crop_code in solution.assignment:
        crop = problem.knowledge.crops.get(crop_code or "")
        if crop is None:
            continue
        for t in crop.traits.values():
            key = (t.pack_version, t.source_key)
            if key not in trait_sources:
                trait_sources[key] = {
                    "type": "knowledge_source",
                    "source_key": t.source_key,
                    "citation_text": t.citation_text,
                    "pack_code": t.pack_code,
                    "pack_version": t.pack_version,
                }
    evidence_refs.extend(trait_sources.values())
    if problem.farm.soil is not None:
        evidence_refs.append({
            "type": "soil_evidence",
            "evidence_class": problem.farm.soil_evidence_class,
            "note": "Latest soil property observations for this field.",
        })

    # data limitations
    limitations: list[str] = []
    if problem.synthetic_evidence:
        limitations.append(
            "Climate evidence is SYNTHETIC test data — this strategy is a "
            "demonstration and must never be treated as real farm evidence."
        )
    if problem.farm.soil is not None and problem.farm.soil_evidence_class == "global_soil_prediction":
        limitations.append(
            "Soil values are SoilGrids 0-5 cm model predictions, not lab measurements."
        )
    limitations.append(
        "Crop water figures are FAO-56 single-Kc screening estimates with sowing "
        "assumed at season start — superseded by the daily water balance (Milestone 7)."
    )
    if problem.knowledge.confirmed_rule_count == 0:
        limitations.append(
            "No confirmed-regional rotation rules are loaded: rotation breaks are "
            "advisory here and were NOT enforced as hard constraints."
        )
    limitations.append(
        "Calendar windows and many trait values are reference knowledge pending "
        "regional validation."
    )

    # expected benefits & trade-offs vs the other strategies
    benefits: list[str] = []
    trade_offs: list[str] = []
    others = [s for s in all_solutions if s.strategy_key != solution.strategy_key]
    for code, crit in criteria.items():
        if not crit.evaluable or crit.raw_value is None:
            continue
        better: list[str] = []
        worse: list[str] = []
        direction = crit.direction
        for other in others:
            oc = next((c for c in other.criteria if c.criterion_code == code), None)
            if oc is None or not oc.evaluable or oc.raw_value is None:
                continue
            if direction == "maximize":
                if crit.raw_value > oc.raw_value:
                    better.append(other.strategy_key)
                elif crit.raw_value < oc.raw_value:
                    worse.append(other.strategy_key)
            else:
                if crit.raw_value < oc.raw_value:
                    better.append(other.strategy_key)
                elif crit.raw_value > oc.raw_value:
                    worse.append(other.strategy_key)
        if better:
            benefits.append(
                f"{code}: best among compared strategies (vs {', '.join(better)})."
            )
        if worse:
            trade_offs.append(
                f"{code}: worse than {', '.join(worse)} — a deliberate trade-off of "
                "this preference profile."
            )

    # local expert validation requirements
    validation_required: list[str] = []
    seen_rules: set[str] = set()
    for season_assessments in problem.candidates.values():
        for crop_code, assessment in sorted(season_assessments.items()):
            for reason in assessment.reasons:
                if reason.get("kind") == "rotation_knowledge":
                    for ref in reason.get("source_refs", []):
                        rule_code = ref.get("rule_code")
                        if ref.get("validation_status") != "confirmed_regional" and rule_code not in seen_rules:
                            seen_rules.add(rule_code)
                            validation_required.append(
                                f"Rotation rule '{rule_code}' is "
                                f"'{ref.get('validation_status')}' — needs regional "
                                "confirmation by a local agronomist before enforcement."
                            )
    if problem.knowledge.reference_rule_count:
        validation_required.append(
            f"{problem.knowledge.reference_rule_count} reference rule(s) loaded — "
            "none are regionally confirmed; see the knowledge browser for citations."
        )

    return {
        "why_generated": why_generated,
        "recommendation": recommendation,
        "constraints_checked": [
            {
                "constraint_code": c.constraint_code,
                "status": c.status,
                "description": c.description,
                "detail": c.detail,
                "rule_codes": list(c.rule_codes),
                "source_refs": list(c.source_refs),
            }
            for c in solution.constraints_checked
        ],
        "criteria_evaluation": [
            {
                "criterion_code": c.criterion_code,
                "raw_value": c.raw_value,
                "unit": c.unit,
                "direction": c.direction,
                "normalized": c.normalized,
                "evaluable": c.evaluable,
                "missing_evidence": list(c.missing_evidence),
                "derivation": c.derivation,
                "source_refs": list(c.source_refs),
            }
            for c in solution.criteria
        ],
        "evidence_references": evidence_refs,
        "data_limitations": limitations,
        "expected_benefits": benefits,
        "risks_trade_offs": trade_offs,
        "local_expert_validation_required": validation_required,
        "units": dict(CRITERION_UNITS),
        "directions": dict(CRITERION_DIRECTIONS),
    }
